from __future__ import annotations

from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field

from app.database.repositories import Repository
from app.dependencies import chat_rate_limit, get_repo
from app.llm.assistant import chat
from app.recommendations.engine import ProductNotFound
from app.security.permissions import CurrentUser, optional_user, require_user
from app.services import chat_service

router = APIRouter(prefix="/api/assistant", tags=["assistant"])


class ChatMessage(BaseModel):
    role: str = Field(pattern="^(user|assistant)$")
    content: str = Field(max_length=4000)


class ChatPreferences(BaseModel):
    target_price: float | None = Field(default=None, gt=0)
    max_budget: float | None = Field(default=None, gt=0)
    deadline_days: int | None = Field(default=None, ge=0, le=365)
    max_monthly_emi: float | None = Field(default=None, gt=0)
    preferred_tenure_months: int | None = Field(default=None, ge=1, le=60)
    objective: str | None = Field(default=None, pattern="^(lowest_total_cost|lowest_monthly_payment|shortest_tenure|lowest_interest|balanced)$")
    user_banks: list[str] = Field(default_factory=list, max_length=20)


class ChatRequest(BaseModel):
    message: str = Field(min_length=1, max_length=2000)
    product_id: str | None = None
    history: list[ChatMessage] = Field(default_factory=list, max_length=20)
    preferences: ChatPreferences = Field(default_factory=ChatPreferences)


@router.post("/chat", dependencies=[Depends(chat_rate_limit)],
             summary="Ask the purchase advisor (read-only; vendor pages only fetched for EMI/vendor/review questions)")
async def chat_endpoint(req: ChatRequest, repo: Repository = Depends(get_repo),
                        user: CurrentUser | None = Depends(optional_user)) -> dict:
    try:
        r = await chat(repo, req.message, product_id=req.product_id,
                       history=[m.model_dump() for m in req.history],
                       preferences=req.preferences.model_dump(exclude_none=True), user_id=user.id if user else None)
    except ProductNotFound:
        raise HTTPException(404, "Product not found") from None
    if user:
        repo.log_activity(user.id, "assistant_chat", f"Asked the assistant: {req.message[:200]}",
                          product_id=(r.get("intent") or {}).get("product_id"))
    return r


# ---------------------------------------------------------------- saved conversations (sign-in required)
class SessionIn(BaseModel):
    id: UUID                                       # generated by the browser so a retried create is idempotent
    title: str | None = Field(default=None, max_length=120)
    product_id: str | None = None


class RenameIn(BaseModel):
    title: str = Field(min_length=1, max_length=120)


class TurnIn(BaseModel):
    request_id: UUID                               # generated by the browser; re-send the same id after a failure
    message: str = Field(min_length=1, max_length=2000)
    product_id: str | None = None
    preferences: ChatPreferences = Field(default_factory=ChatPreferences)


def message_out(m: dict) -> dict:
    return {"id": m["id"], "request_id": str(m["request_id"]), "role": m["role"], "content": m["content"],
            "status": m["status"], "meta": m["meta"], "created_at": m["created_at"]}


def own_session(repo: Repository, session_id: UUID, user: CurrentUser) -> dict:
    s = repo.get_chat_session(session_id)
    if not s or s["user_id"] != user.id:
        raise HTTPException(404, "Conversation not found")
    return s


@router.get("/sessions", summary="The signed-in user's saved conversations, most recent first")
def list_sessions(repo: Repository = Depends(get_repo), user: CurrentUser = Depends(require_user)) -> list[dict]:
    return repo.list_chat_sessions(user.id)


@router.post("/sessions", summary="Start a conversation (idempotent for the same id)")
def create_session(body: SessionIn, repo: Repository = Depends(get_repo), user: CurrentUser = Depends(require_user)) -> dict:
    s = repo.create_chat_session(body.id, user.id, body.title, body.product_id)
    if s["user_id"] != user.id:
        raise HTTPException(409, "Conversation id already in use")
    return s


@router.get("/sessions/{session_id}", summary="One conversation with all its messages")
def get_session(session_id: UUID, repo: Repository = Depends(get_repo), user: CurrentUser = Depends(require_user)) -> dict:
    s = own_session(repo, session_id, user)
    return {**s, "messages": [message_out(m) for m in repo.chat_messages(session_id)]}


@router.post("/sessions/{session_id}/rename", summary="Rename a conversation")
def rename_session(session_id: UUID, body: RenameIn, repo: Repository = Depends(get_repo),
                   user: CurrentUser = Depends(require_user)) -> dict:
    own_session(repo, session_id, user)
    return repo.rename_chat_session(session_id, body.title.strip())


@router.delete("/sessions/{session_id}", summary="Delete a conversation from the user's history")
def delete_session(session_id: UUID, repo: Repository = Depends(get_repo), user: CurrentUser = Depends(require_user)) -> dict:
    own_session(repo, session_id, user)
    repo.delete_chat_session(session_id)
    return {"deleted": True}


@router.post("/sessions/{session_id}/messages", dependencies=[Depends(chat_rate_limit)],
             summary="Ask a question in a conversation. Safe to retry with the same request_id after a dropped connection")
async def send_message(session_id: UUID, body: TurnIn, repo: Repository = Depends(get_repo),
                       user: CurrentUser = Depends(require_user)) -> dict:
    s = own_session(repo, session_id, user)
    row = await chat_service.answer(repo, s, body.request_id, body.message.strip(), user=user, product_id=body.product_id,
                                    preferences=body.preferences.model_dump(exclude_none=True))
    return {"session_id": str(session_id), "title": s["title"], "message": message_out(row)}
