-- Accounts, activity history and persistent assistant conversations.
--
-- Sign-in itself is Supabase Auth (email + password); this schema only stores what the app needs
-- about each account. user_id is the Supabase auth user id (JWT "sub"). There is deliberately no
-- foreign key to auth.users so the migration also runs on a plain PostgreSQL test database.
set search_path to smartbuy, public;

create table profiles (
    user_id      uuid primary key,
    email        text,
    display_name text check (display_name is null or length(display_name) <= 80),
    role         text not null default 'user' check (role in ('user', 'admin')),
    is_disabled  boolean not null default false,
    created_at   timestamptz not null default now(),
    last_seen_at timestamptz not null default now()
);
create index profiles_email_idx on profiles (lower(email));

-- One row per thing a signed-in user did: assistant questions, advisor recommendations,
-- notification views, saved targets, sign-ins, and admin actions on other accounts.
create table activity_log (
    id         bigserial primary key,
    user_id    uuid not null,
    kind       text not null check (kind in ('sign_in', 'assistant_chat', 'recommendation', 'notifications_viewed',
                                             'target_saved', 'admin_action')),
    product_id text,
    summary    text not null check (length(summary) <= 500),
    payload    jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);
create index activity_log_user_idx on activity_log (user_id, created_at desc);
create index activity_log_created_idx on activity_log (created_at desc);

create table chat_sessions (
    id         uuid primary key,
    user_id    uuid not null,
    title      text not null default 'New conversation' check (length(title) <= 120),
    product_id text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    deleted_at timestamptz
);
create index chat_sessions_user_idx on chat_sessions (user_id, updated_at desc);

-- A user message and its answer share request_id (generated by the browser before sending).
-- The unique (session_id, request_id, role) makes re-sending after a dropped connection safe:
-- the server finds the existing question/answer instead of creating a duplicate.
-- status: user rows are always 'complete'; an assistant row is 'pending' while the answer is
-- being generated, then 'complete' or 'failed'.
create table chat_messages (
    id         bigserial primary key,
    session_id uuid not null references chat_sessions(id) on delete cascade,
    request_id uuid not null,
    role       text not null check (role in ('user', 'assistant')),
    content    text not null default '',
    status     text not null default 'complete' check (status in ('pending', 'complete', 'failed')),
    meta       jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (session_id, request_id, role)
);
create index chat_messages_session_idx on chat_messages (session_id, id);

do $$
declare t text;
begin
    foreach t in array array['profiles', 'activity_log', 'chat_sessions', 'chat_messages'] loop
        execute format('alter table smartbuy.%I enable row level security', t);
    end loop;

    if exists (select 1 from pg_namespace where nspname = 'auth')
       and exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                   where n.nspname = 'auth' and p.proname = 'uid') then
        execute 'create policy profiles_owner_read on smartbuy.profiles for select using (auth.uid() = user_id)';
        execute 'create policy activity_owner_read on smartbuy.activity_log for select using (auth.uid() = user_id)';
        execute 'create policy chat_sessions_owner on smartbuy.chat_sessions for select using (auth.uid() = user_id)';
        execute 'create policy chat_messages_owner on smartbuy.chat_messages for select
                 using (exists (select 1 from smartbuy.chat_sessions s
                                where s.id = session_id and s.user_id = auth.uid()))';
    end if;
end $$;
